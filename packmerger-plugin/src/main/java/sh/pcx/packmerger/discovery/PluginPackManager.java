package sh.pcx.packmerger.discovery;

import io.papermc.paper.threadedregions.scheduler.ScheduledTask;
import org.bukkit.Bukkit;
import sh.pcx.packmerger.PackMergerBootstrap;
import sh.pcx.packmerger.PluginLogger;
import sh.pcx.packmerger.config.ConfigManager;
import sh.pcx.packmerger.remote.FetchResult;
import sh.pcx.packmerger.remote.RemoteSpec;

import java.io.File;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicInteger;

/**
 * Discovers resource packs generated by other installed plugins and stages each
 * into {@code packs/.plugin-packs/<alias>.zip} so the merge pipeline consumes
 * them by alias, the same way {@link sh.pcx.packmerger.remote.RemotePackManager}
 * stages remote packs into {@code packs/.remote-cache/}.
 *
 * <p>{@link #stageAll()} runs before every merge. A low-frequency watcher
 * ({@code plugin-packs.watch}) polls the resolved source paths and triggers a
 * merge when a plugin rebuilds its pack, so {@code /oraxen reload}-style rebuilds
 * need no {@code /pm reload}. The staging rules themselves (stability window,
 * validation, cluster union, stale cleanup) live in {@link PluginPackStager}.</p>
 */
public class PluginPackManager {

    /** Sub-directory of {@code packs/} where detected plugin packs are staged. */
    public static final String STAGE_DIR = ".plugin-packs";

    /** Consecutive deferred passes re-merged automatically when the watcher is off. */
    private static final int MAX_DEFERRED_RETRIES = 10;

    private final PackMergerBootstrap plugin;
    private final PluginLogger logger;
    private final File stageDir;

    private volatile PluginPackStager stager;
    private volatile ScheduledTask watchTask;

    /** Re-download URL-published packs on the next pass (startup and /pm reload). */
    private volatile boolean refreshRemote = true;

    private final AtomicInteger deferredRetries = new AtomicInteger();

    /** Detected-but-not-merged advisory for ops, or {@code null} when all good. */
    private volatile String advisory;

    /** Report of the last staging pass, for /pm status. */
    private volatile PluginPackStager.Report lastReport;

    public PluginPackManager(PackMergerBootstrap plugin) {
        this.plugin = plugin;
        this.logger = plugin.getPluginLogger();
        this.stageDir = new File(plugin.getPacksFolder(), STAGE_DIR);
    }

    /** @return {@code packs/.plugin-packs/}, created on demand */
    public File stageDir() {
        if (!stageDir.exists()) stageDir.mkdirs();
        return stageDir;
    }

    /** The server's {@code plugins/} directory (parent of {@code plugins/PackMerger/}). */
    private File pluginsFolder() {
        return plugin.getLoader().getDataFolder().getParentFile();
    }

    /** Rebuilds the stager from current config (called on enable and on reload). */
    public void reconfigure() {
        ConfigManager cfg = plugin.getConfigManager();
        stager = new PluginPackStager(pluginsFolder(), stageDir(),
                plugin.getMergeEngine() == null ? List.of() : plugin.getMergeEngine().getMergeStrategies(),
                cfg.getPluginPacksStabilityPolls(), cfg.getPluginPacksStabilityIntervalMillis(),
                Thread::sleep, this::fetchRemote,
                note -> logger.warning("[plugin-packs] " + note));
        refreshRemote = true;
        deferredRetries.set(0);
    }

    private PluginPackStager stager() {
        if (stager == null) reconfigure();
        return stager;
    }

    /**
     * Built-in adapters with operator overrides applied, followed by
     * operator-defined adapters, keyed by alias.
     */
    Map<String, PluginPackAdapter> effectiveAdapters(boolean warn) {
        Map<String, PluginPackAdapter.PluginPackOverride> overrides =
                plugin.getConfigManager().getPluginPackOverrides();
        Map<String, PluginPackAdapter> out = new LinkedHashMap<>();
        for (PluginPackAdapter a : PluginPackAdapter.builtIns()) {
            out.put(a.alias(), a.withOverride(overrides.get(a.alias())));
        }
        for (Map.Entry<String, PluginPackAdapter.PluginPackOverride> e : overrides.entrySet()) {
            if (out.containsKey(e.getKey())) continue;
            PluginPackAdapter custom = PluginPackAdapter.custom(e.getKey(), e.getValue());
            if (custom == null) {
                if (warn) logger.warning("[plugin-packs] sources." + e.getKey()
                        + " is not a built-in adapter and declares no path or url; ignoring it");
                continue;
            }
            out.put(custom.alias(), custom);
        }
        return out;
    }

    private boolean installed(PluginPackAdapter a) {
        return a.pluginName() == null || Bukkit.getPluginManager().getPlugin(a.pluginName()) != null;
    }

    private boolean enabled(PluginPackAdapter a) {
        PluginPackAdapter.PluginPackOverride o = plugin.getConfigManager().getPluginPackOverrides().get(a.alias());
        return o == null || o.enabled();
    }

    /**
     * Stages every enabled, detected plugin's current generated pack into
     * {@code packs/.plugin-packs/} and removes stale staged packs. Safe to call
     * before each merge; blocks for the stability window only when a source changed.
     *
     * @return the number of packs (re)staged this pass
     */
    public int stageAll() {
        ConfigManager cfg = plugin.getConfigManager();
        if (!cfg.isPluginPacksEnabled()) {
            advisory = null;
            lastReport = null;
            for (String alias : stager().clear()) {
                logger.info("[plugin-packs] removed staged pack '" + alias + "' (plugin-packs.enabled is false)");
            }
            return 0;
        }

        List<PluginPackStager.Entry> entries = new ArrayList<>();
        for (PluginPackAdapter a : effectiveAdapters(true).values()) {
            entries.add(new PluginPackStager.Entry(a, enabled(a), installed(a)));
        }
        boolean refresh = refreshRemote;
        PluginPackStager.Report report = stager().run(entries, refresh);
        if (refresh) refreshRemote = false;
        lastReport = report;

        List<String> notMerged = new ArrayList<>();
        for (PluginPackStager.Outcome o : report.outcomes()) {
            String who = o.pluginName() != null ? o.pluginName() : o.alias();
            switch (o.status()) {
                case STAGED -> logger.info("[plugin-packs] staged " + who + " as '" + o.alias() + "' ← " + o.detail());
                case FETCHED -> logger.info("[plugin-packs] using " + who + " pack '" + o.alias() + "' (" + o.detail() + ")");
                case UNCHANGED -> logger.debug("[plugin-packs] " + who + " unchanged, reusing staged '" + o.alias() + "'");
                case DEFERRED -> logger.info("[plugin-packs] " + who + ": " + o.detail());
                case INVALID -> logger.warning("[plugin-packs] skipped " + who + " ('" + o.alias() + "'): " + o.detail());
                case FAILED -> logger.warning("[plugin-packs] failed to stage " + who + " ('" + o.alias() + "'): " + o.detail());
                default -> { }
            }
            if (!o.advisory()) continue;
            String hint = switch (o.status()) {
                case DISABLED -> "disabled in config";
                case NOT_FOUND -> "no generated pack found; build its pack, or set plugin-packs.sources."
                        + o.alias() + ".path";
                case INVALID -> "not a resource pack: " + o.detail();
                default -> o.detail();
            };
            notMerged.add(who + " (" + hint + ")");
        }
        for (String alias : report.pruned()) {
            logger.info("[plugin-packs] removed stale staged pack '" + alias
                    + "' (adapter disabled, plugin removed, or its source is gone or invalid)");
        }

        // ItemsAdder zip protection / JSON compression (and its own hosting) are reported
        // by the competing-host check (/pm status, admin join notice, /pm fixup).

        advisory = notMerged.isEmpty() ? null
                : "PackMerger: pack-generating plugins installed but not merged → " + String.join("; ", notMerged);
        if (advisory != null) logger.warning("[plugin-packs] " + advisory);

        scheduleDeferredRetry(report);
        return report.stagedCount();
    }

    /**
     * A deferred source (still being written) is picked up by the watcher once it
     * settles. With the watcher off, re-run the merge a few times instead.
     */
    private void scheduleDeferredRetry(PluginPackStager.Report report) {
        if (!report.hasDeferred()) {
            deferredRetries.set(0);
            return;
        }
        if (plugin.getConfigManager().isPluginPacksWatchEnabled()) return;
        if (deferredRetries.incrementAndGet() > MAX_DEFERRED_RETRIES) {
            logger.warning("[plugin-packs] a plugin's pack kept changing; giving up until the next /pm merge");
            return;
        }
        long delay = Math.max(5, plugin.getConfigManager().getPluginPacksWatchIntervalSeconds());
        Bukkit.getAsyncScheduler().runDelayed(plugin.getLoader(), t -> plugin.mergeAndUpload(null),
                delay, TimeUnit.SECONDS);
    }

    /** Downloads a URL-published plugin pack into the stage dir via the remote pack fetcher. */
    private PluginPackStager.FetchOutcome fetchRemote(PluginPackAdapter a, File dir) {
        if (plugin.getRemotePackManager() == null) {
            return new PluginPackStager.FetchOutcome(false, false, "remote fetcher not ready");
        }
        FetchResult r = plugin.getRemotePackManager().fetchInto(
                new RemoteSpec(a.alias(), a.url(), "on-startup", RemoteSpec.AuthSpec.NONE, false), dir);
        boolean usable = r.status() != FetchResult.Status.ERROR_NO_CACHE
                && r.status() != FetchResult.Status.SKIPPED_BY_POLICY;
        return new PluginPackStager.FetchOutcome(usable, r.status() == FetchResult.Status.FETCHED,
                r.status().name().toLowerCase().replace('_', ' ') + (r.detail() == null ? "" : ": " + r.detail()));
    }

    // -------------------------------------------------------------------------
    // Watcher
    // -------------------------------------------------------------------------

    /** Starts polling resolved plugin source paths, if enabled in config. */
    public void startWatcher() {
        stopWatcher();
        ConfigManager cfg = plugin.getConfigManager();
        if (!cfg.isPluginPacksEnabled() || !cfg.isPluginPacksWatchEnabled()) return;
        long interval = cfg.getPluginPacksWatchIntervalSeconds();
        watchTask = Bukkit.getAsyncScheduler().runAtFixedRate(plugin.getLoader(), t -> pollOnce(),
                interval, interval, TimeUnit.SECONDS);
        logger.debug("[plugin-packs] watching plugin pack sources every " + interval + "s");
    }

    /** Stops the source watcher. Safe to call when it is not running. */
    public void stopWatcher() {
        ScheduledTask t = watchTask;
        watchTask = null;
        if (t != null) t.cancel();
    }

    private void pollOnce() {
        try {
            if (plugin.isMerging() || !plugin.getConfigManager().isPluginPacksEnabled()) return;
            List<PluginPackAdapter> active = new ArrayList<>();
            for (PluginPackAdapter a : effectiveAdapters(false).values()) {
                if (!a.isRemote() && enabled(a) && installed(a)) active.add(a);
            }
            if (stager().pollForChanges(active)) {
                logger.info("[plugin-packs] a plugin's generated pack changed on disk; re-merging");
                plugin.mergeAndUpload(null);
            }
        } catch (RuntimeException e) {
            logger.debug("[plugin-packs] watcher poll failed: " + e.getMessage());
        }
    }

    /** Re-download URL-published plugin packs on the next pass (used by /pm reload). */
    public void markRemoteRefresh() {
        refreshRemote = true;
    }

    /**
     * @return a one-line advisory naming installed pack-generating plugins that
     *         are <em>not</em> being merged (disabled, missing output, invalid
     *         source, or staging failure), or {@code null} when everything detected
     *         is merged. Populated by {@link #stageAll()}.
     */
    public String getAdvisoryMessageOrNull() {
        return advisory;
    }

    /**
     * @return one entry per installed pack-generating plugin from the last pass, as
     *         {@code "<plugin> (<alias>): <state>"} (empty before the first pass)
     */
    public List<String> getIntegrationStates() {
        PluginPackStager.Report r = lastReport;
        if (r == null) return List.of();
        List<String> out = new ArrayList<>();
        for (PluginPackStager.Outcome o : r.outcomes()) {
            String state = switch (o.status()) {
                case STAGED, UNCHANGED, FETCHED -> "merged";
                case DEFERRED -> "waiting for its pack to finish writing";
                case DISABLED -> "disabled in config";
                case NOT_FOUND -> "installed, no generated pack found";
                case INVALID -> "not a resource pack";
                case FAILED -> "failed";
                case NOT_INSTALLED -> null;
            };
            if (state == null) continue;
            String who = o.pluginName() != null ? o.pluginName() + " (" + o.alias() + ")" : o.alias();
            out.add(who + ": " + state);
        }
        return out;
    }

    /** @return aliases merged from plugins on the last pass (empty before the first pass) */
    public List<String> getMergedAliases() {
        PluginPackStager.Report r = lastReport;
        return r == null ? List.of() : r.mergedAliases();
    }
}
